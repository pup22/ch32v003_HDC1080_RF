#pragma once

// Драйвер DS18B20 для CH32V003 + ch32fun (1-Wire на одном пине, один датчик на шине).
//
// Подключение: DQ -> пин (по умолчанию PC2) + подтяжка 4,7 кОм к VCC датчика.
// Питание датчика с GPIO: VCC = PC3, GND = PC4. Подтяжку подключать именно к PC3 (выключаемому
// питанию), а не к постоянной шине: иначе во сне через неё потечёт ток в линию, прижатую к земле.
//
// Требования к тактированию: SysTick считает HCLK, HCLK = FUNCONF_SYSTEM_CORE_CLOCK (3 МГц в этом
// проекте). Прерывания на время обмена должны быть выключены (в ch32fun по умолчанию так и есть).

#include <stdint.h>
#include <stdbool.h>
#include "ch32fun.h"

// Разрешение преобразования: 9..12 бит. Время преобразования (максимум по даташиту):
// 9 бит = 94 мс, 10 = 188 мс, 11 = 375 мс, 12 = 750 мс. Шаг: 0,5 / 0,25 / 0,125 / 0,0625 °C.
#ifndef DS18B20_RESOLUTION_BITS
#define DS18B20_RESOLUTION_BITS 11
#endif

// Сколько ждать окончания преобразования (мс). С запасом на 12 бит, если запись
// разрешения не прошла и датчик работает с настройками по умолчанию.
#ifndef DS18B20_CONVERSION_TIMEOUT_MS
#define DS18B20_CONVERSION_TIMEOUT_MS 900
#endif

// Сколько раз пробовать полный цикл измерения при ошибке (нет ответа, ошибка CRC)
#ifndef DS18B20_ATTEMPTS
#define DS18B20_ATTEMPTS 2
#endif

// Настроить пин 1-Wire (открытый сток, линия отпущена). Вызывать после включения питания датчика.
void ds18b20_init(uint8_t pin);

// Импульс сброса и проверка присутствия. false: шина замкнута на землю или датчик не отвечает.
bool ds18b20_present(void);

// Записать разрешение (9..12 бит) в ОЗУ датчика. EEPROM не трогается.
bool ds18b20_set_resolution(uint8_t bits);

// Запустить преобразование температуры (команда Convert T).
bool ds18b20_start_conversion(void);

// Ждать окончания преобразования (опрос слотами чтения каждые 5 мс). false: тайм-аут.
bool ds18b20_wait_conversion(uint16_t timeout_ms);

// Прочитать 9 байт блокнота (scratchpad) и проверить CRC.
bool ds18b20_read_scratchpad(uint8_t sp[9]);

// Перевод сырого значения (1/16 °C) в сотые доли градуса. config = байт 4 блокнота:
// по нему отбрасываются неопределённые младшие биты при разрешении ниже 12 бит.
int16_t ds18b20_raw_to_x100(int16_t raw, uint8_t config);

// Полный цикл: разрешение, преобразование, ожидание, чтение, CRC (с повтором при ошибке).
// Результат в сотых долях °C (например, 2306 = 23,06 °C). Без плавающей точки.
bool ds18b20_measure_x100(int16_t *t_x100);
